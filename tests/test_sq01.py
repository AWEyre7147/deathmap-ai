        historical=self.root/'outputs/synthetic-v01/manifest.json'
        disk.write(historical,{'historical':'unchanged'})
        baseline={p.relative_to(self.root).as_posix():disk.sha(p) for p in [historical,self.root/config.INDEX,self.root/config.INDEX_SUMMARY]}
        disk.write(self.root/'docs/sq01-preservation.json',{'recorded_at':'synthetic-date','before':baseline})
        proposal={'plan_version':'immune-crispr-coculture-v03.1','status':'proposed_for_owner_review','synthetic':'prior review'}
