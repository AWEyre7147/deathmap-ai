def response(rows=None, count=0, code=200, headers=None):
    return {'http_status':code,'headers':headers or {},'body':json.dumps({'count':count,'datasets':rows or []}).encode()}


def native(identifier='synthetic-a', repository='synthetic-repository'):
    return {'source':repository,'id':identifier,'title':'Synthetic title','description':'Original synthetic description'}


def screen(identifier, publication, text):
    return {'SCREEN_ID':identifier,'SOURCE_TYPE':'pubmed','SOURCE_ID':publication,
        'SCREEN_NAME':'Synthetic screen','SCREEN_FORMAT':'pooled','METHODOLOGY':'CRISPR',
        'NOTES':text,'AUTHOR':'synthetic citation','CELL_LINE':'synthetic line'}


class SQ01Tests(unittest.TestCase):
    def setUp(self):
        self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup)
        self.root=Path(self.tmp.name);self.folder=self.root/'omics';self.folder.mkdir()
        self.plan=config.build_plan();self.digest=config.digest(self.plan)
        self.state=omics.initial(self.digest)
        self.qids=list(self.state['queries']);self.queries=self.plan['resources'][0]['queries']
        self.calls=[];self.sleeps=[]

    def run_engine(self, fetch=None, state=None):
        callback=fetch or (lambda *args:response())
        def record(url,timeout):
            self.calls.append(url)
            return callback(url,timeout)
        return omics.run(self.folder,state or self.state,self.digest,record,self.sleeps.append,emit=lambda _:None)

    def index(self, rows):
        disk.write(self.root/config.INDEX,rows)
        disk.write(self.root/config.INDEX_SUMMARY,{'screens_retrieved':len(rows),'retrieved_at':'original-cache-date'})

    def test_exact_question_family_and_disabled_stages(self):
        self.assertEqual(self.plan['scientific_questions'],[{'question_id':'SQ01','question':'pooled CRISPR knockout screens in cancer cells under immune selection'}])
        expected=[
            'pooled AND CRISPR AND knockout AND screens AND "cancer cells" AND immune AND selection',
            'CRISPR AND knockout AND "cancer cells" AND immune',
            'pooled AND CRISPR AND knockout AND screen AND "cancer cells" AND immune AND selection',
            'pooled AND CRISPR AND knockout AND screens AND "cancer cell" AND immune AND selection',
            'pooled AND CRISPR AND knockout AND screens AND "tumor cell" AND immune AND selection',
            'pooled AND CRISPR AND knockout AND "cancer cells" AND coculture',
            'pooled AND CRISPR AND knockout AND "cancer cells" AND co-culture',
            'pooled AND CRISPR AND knockout AND "cancer cells" AND "co culture"',
            'pooled AND CRISPR AND knockout AND "cancer cells" AND "immune killing"',
            'pooled AND CRISPR AND knockout AND "cancer cells" AND "immune pressure"',
            'pooled AND CRISPR AND knockout AND "cancer cells" AND "immune selection"']
        self.assertEqual([q['submitted_query'] for q in self.queries],expected)
        self.assertEqual(self.qids,[f'OM3-SQ01-Q{i:02}' for i in range(1,12)])
